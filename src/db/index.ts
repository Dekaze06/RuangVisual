async function createDbInstance(): Promise<DbInstance> {
  const databaseUrl = process.env.DATABASE_URL?.trim();

  if (databaseUrl) {
    const pool = new pg.Pool({ connectionString: databaseUrl });
    await pool.query(DDL_SQL);
    const db = drizzlePg(pool, { schema });
    await seedDatabase(db);
    return db;
  }

  const isServerless = Boolean(process.env.VERCEL || process.env.AWS_LAMBDA_FUNCTION_NAME);
  const dataDir = isServerless
    ? path.resolve('/tmp', 'ruang-visual-data', 'pglite')
    : path.resolve(process.cwd(), '.data', 'pglite');

  fs.mkdirSync(dataDir, { recursive: true });
  const client = new PGlite(dataDir);
  await client.exec(DDL_SQL);
  const db = drizzlePglite(client, { schema });
  await seedDatabase(db);
  return db;
}

export async function getDb(): Promise<DbInstance> {
  if (!globalThis.__ruangVisualDbPromise) {
    globalThis.__ruangVisualDbPromise = createDbInstance();
  }
  return globalThis.__ruangVisualDbPromise;
}

